# the only code not copied: constructors that take events directly instead of a Mongo-backed Memory
STUBS = {
    "CausalLinkIndexer": "class CausalLinkIndexer:\n    MAX_LINKS_PER_TYPE: int = 15\n\n",
    "AbsenceCatalogBuilder": "class AbsenceCatalogBuilder:\n",
}
INIT = "    def __init__(self, events, mem=None):\n        self._events = events\n        self._mem = mem\n\n"


def segment(lines: list[str], node: ast.stmt) -> str:
    # line slice, not get_source_segment: decorators such as @dataclass must survive the copy
    decorators = getattr(node, "decorator_list", [])
    start = min([d.lineno for d in decorators] + [node.lineno]) - 1
    return "".join(lines[start : node.end_lineno])


def extract(source: str) -> str:
    tree = ast.parse(source)
    lines = source.splitlines(keepends=True)
    out: list[str] = []
    wanted = set(CONSTANTS) | set(FUNCTIONS) | set(CLASSES)
    for node in tree.body:
        name = (
            node.targets[0].id
            if isinstance(node, ast.Assign) and isinstance(node.targets[0], ast.Name)
            else node.target.id
            if isinstance(node, ast.AnnAssign) and isinstance(node.target, ast.Name)
            else getattr(node, "name", None)
        )
        if name in wanted:
            out.append(segment(lines, node).rstrip("\n"))
        if isinstance(node, ast.ClassDef) and node.name in METHODS:
            copied = METHODS[node.name]
            body = [
                segment(lines, m).rstrip("\n") for m in node.body if isinstance(m, ast.FunctionDef) and m.name in copied
            ]
            out.append(STUBS[node.name] + INIT + "\n\n".join(body))
    return "\n\n\n".join(out) + "\n"


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("source", type=Path, help="orgforge/eval/eval_harness.py at the pinned commit")
    parser.add_argument("--commit", required=True)
    parser.add_argument("--out", type=Path, default=Path("src/constellation/_vendor/orgforge_causal.py"))
    args = parser.parse_args(argv)
    text = args.source.read_text()
    digest = hashlib.sha256(text.encode()).hexdigest()
    args.out.write_text(HEADER.format(commit=args.commit, digest=digest) + extract(text))
    print(f"wrote {args.out} from sha256 {digest[:12]}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
